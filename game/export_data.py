"""Writes game/js/data.js from the Python sources (plants, stat sets, lore, labels, system prompt), so the
game never drifts from the environment. Run from the repository root after changing any of them:

    python3 game/export_data.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from environment.brewer import LEVELS, MAX_PLANTS, MIN_PLANTS, PLANTS, STAT_SETS  # noqa: E402
from environment.goals import STAT_NAMES  # noqa: E402
from environment.knowledge_base import LABELS  # noqa: E402
from environment.lore import LORE  # noqa: E402
from LLM.episode import MAX_CALLS_PER_TURN  # noqa: E402

DEFAULTS = {  # scripts/run_experiment.sh
    "garden_size": 10,
    "growth_min": 2,
    "growth_max": 6,
    "goals": "target:I:10",
    "allergy": "none",
    "lore": True,
    "turn_cap": 150,
}


def main() -> None:
    data = {
        "PLANTS": list(PLANTS),
        "MIN_PLANTS": MIN_PLANTS,
        "MAX_PLANTS": MAX_PLANTS,
        "LEVELS": list(LEVELS),
        "STAT_SETS": {k: list(v) for k, v in STAT_SETS.items()},
        "STAT_NAMES": STAT_NAMES,
        "LABELS": list(LABELS),
        "LORE": [[a, b, text] for (a, b), text in LORE.items()],
        "MAX_FAILURES": 3,
        "MAX_CALLS_PER_TURN": MAX_CALLS_PER_TURN,
        "SYSTEM_PROMPT": (ROOT / "prompts" / "system.txt").read_text(encoding="utf-8"),
        "DEFAULTS": DEFAULTS,
    }
    body = json.dumps(data, indent=2, ensure_ascii=False)
    out = ROOT / "game" / "js" / "data.js"
    out.write_text(
        "// Generated by game/export_data.py from the Python sources. Do not edit by hand.\n"
        f"const PG_DATA = {body};\n"
        'if (typeof module !== "undefined") module.exports = PG_DATA;\n',
        encoding="utf-8",
    )
    print(f"Wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
